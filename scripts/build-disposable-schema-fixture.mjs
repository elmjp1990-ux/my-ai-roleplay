import fs from "node:fs";

const ROOT = "supabase/drafts/";

function quoteIdent(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function quoteRole(value) {
  return String(value).toUpperCase() === "PUBLIC" ? "PUBLIC" : quoteIdent(value);
}

function normalizeRelationName(value) {
  const name = String(value);
  return name.includes(".") ? name : `public.${name}`;
}

function qualified(value) {
  const parts = String(value).split(".");
  const schema = parts.length === 1 ? "public" : parts[0];
  const name = parts.length === 1 ? parts[0] : parts[1];
  if (!schema || !name || parts.length > 2) throw new Error(`Expected relation name: ${value}`);
  return `${quoteIdent(schema)}.${quoteIdent(name)}`;
}

function grantLine(privileges, target, grantee, objectKind, grantable = false) {
  if (!privileges.length) return "";
  const grant = [...new Set(privileges)].sort().join(", ");
  return `GRANT ${grant} ON ${objectKind} ${target} TO ${quoteRole(grantee)}${grantable ? " WITH GRANT OPTION" : ""};`;
}

function commentLine(target, value) {
  if (value == null) return "";
  return `COMMENT ON ${target} IS '${String(value).replaceAll("'", "''")}';`;
}

function grouped(items, keyFn) {
  const map = new Map();
  for (const item of items) {
    const key = keyFn(item);
    if (!map.has(key)) map.set(key, []);
    map.get(key).push(item);
  }
  return map;
}

export function buildDisposableSchemaSql(structure, routinesSnapshot, security, effectiveGrants) {
  if (structure.capture?.purpose !== "current-state schema-only disposable fixture; not historical migration provenance") {
    throw new Error("Refusing to build from an unverified or historical migration source.");
  }
  const relations = structure.relations ?? [];
  const tables = relations.filter((r) => ["r", "p", "f"].includes(r.kind));
  const sequences = structure.sequences ?? [];
  const columnsByTable = grouped(structure.columns ?? [], (c) => normalizeRelationName(c.table));
  const constraintsByTable = grouped(structure.constraints ?? [], (c) => normalizeRelationName(c.table));
  const constraintIndexNames = new Set(
    (structure.constraints ?? []).filter((c) => ["p", "u"].includes(c.type)).map((c) => c.name),
  );
  const directRelationAcl = security.relation_privileges ?? [];
  const directColumnAcl = security.column_acl ?? [];
  const directSequenceAcl = security.sequence_privileges ?? [];
  const policies = security.policies ?? [];
  const triggers = security.triggers ?? [];
  const routines = routinesSnapshot.routines ?? [];
  const lines = [
    "-- GENERATED CURRENT-STATE SCHEMA FIXTURE.",
    "-- DISPOSABLE ONLY. NOT A HISTORICAL MIGRATION. NOT FOR PRODUCTION.",
    "-- Contains schema metadata only; no application rows or Storage objects.",
    "-- Requires Supabase-managed auth/storage bootstrap and roles to exist first.",
    "SET search_path TO pg_catalog, public, private, extensions, auth, storage, vault, net;",
    "SET check_function_bodies = off;",
    "",
    "CREATE SCHEMA IF NOT EXISTS public;",
    "CREATE SCHEMA IF NOT EXISTS private;",
    "CREATE SCHEMA IF NOT EXISTS extensions;",
    "",
  ];

  lines.push("-- Source extension inventory (platform-provided; no extension is installed by this fixture):");
  for (const ext of structure.extensions ?? []) {
    lines.push(`-- ${ext.name} ${ext.version} (${ext.schema})`);
  }
  lines.push("");

  for (const seq of sequences) {
    const q = `${quoteIdent(seq.schema)}.${quoteIdent(seq.name)}`;
    if (seq.owned_by?.dependency_type === "i") continue; // identity sequences are created by CREATE TABLE.
    lines.push(
      `CREATE SEQUENCE IF NOT EXISTS ${q} AS ${seq.sequence_type}`,
      `  INCREMENT BY ${seq.increment}`,
      `  MINVALUE ${seq.min}`,
      `  MAXVALUE ${seq.max}`,
      `  START WITH ${seq.start}`,
      `  CACHE ${seq.cache}`,
      seq.cycle ? "  CYCLE;" : "  NO CYCLE;",
    );
  }
  lines.push("");

  for (const table of tables) {
    const q = `${quoteIdent(table.schema)}.${quoteIdent(table.name)}`;
    const cols = (columnsByTable.get(`${table.schema}.${table.name}`) ?? [])
      .sort((a, b) => a.ordinal - b.ordinal)
      .map((col) => {
        let definition = `${quoteIdent(col.name)} ${col.type}`;
        if (col.collation) definition += ` COLLATE ${col.collation}`;
        if (col.identity) {
          definition += col.identity === "a"
            ? " GENERATED ALWAYS AS IDENTITY"
            : " GENERATED BY DEFAULT AS IDENTITY";
        } else if (col.generated) {
          if (col.default == null) throw new Error(`Missing generation expression for ${q}.${col.name}`);
          definition += ` GENERATED ALWAYS AS (${col.default}) STORED`;
        } else if (col.default != null) {
          definition += ` DEFAULT ${col.default}`;
        }
        if (col.not_null) definition += " NOT NULL";
        return definition;
      });
    if (!cols.length) throw new Error(`No columns found for ${q}`);
    lines.push(`CREATE TABLE IF NOT EXISTS ${q} (`, cols.map((c) => `  ${c}`).join(",\n"), ");");
    if (table.owner) lines.push(`ALTER TABLE ${q} OWNER TO ${quoteIdent(table.owner)};`);
    const tableComment = commentLine(`TABLE ${q}`, table.comment);
    if (tableComment) lines.push(tableComment);
    for (const col of columnsByTable.get(`${table.schema}.${table.name}`) ?? []) {
      const comment = commentLine(`COLUMN ${q}.${quoteIdent(col.name)}`, col.comment);
      if (comment) lines.push(comment);
    }
    lines.push("");
  }

  const allConstraints = [...constraintsByTable.entries()].flatMap(([tableName, items]) =>
    items.map((constraint) => ({ tableName, constraint })),
  );
  const emitConstraint = ({ tableName, constraint }) => {
    let definition = constraint.definition;
    if (!constraint.validated) definition += " NOT VALID";
    lines.push(`ALTER TABLE ${qualified(tableName)} ADD CONSTRAINT ${quoteIdent(constraint.name)} ${definition};`);
  };
  // Referenced PK/UNIQUE constraints and standalone unique indexes must exist
  // before foreign keys are added, regardless of table-name sort order.
  for (const item of allConstraints.filter((x) => x.constraint.type !== "f")) emitConstraint(item);
  lines.push("");

  for (const index of structure.indexes ?? []) {
    if (constraintIndexNames.has(index.name)) continue;
    lines.push(`${index.definition};`);
  }
  lines.push("");

  for (const item of allConstraints.filter((x) => x.constraint.type === "f")) emitConstraint(item);
  lines.push("");
  for (const seq of sequences) {
    if (seq.owned_by?.dependency_type === "i") continue; // identity sequence owner follows its table.
    if (seq.owner) {
      lines.push(`ALTER SEQUENCE ${qualified(`${seq.schema}.${seq.name}`)} OWNER TO ${quoteIdent(seq.owner)};`);
    }
    if (seq.owned_by?.table && seq.owned_by?.column) {
      lines.push(`ALTER SEQUENCE ${qualified(`${seq.schema}.${seq.name}`)} OWNED BY ${qualified(seq.owned_by.table)}.${quoteIdent(seq.owned_by.column)};`);
    }
  }
  lines.push("");

  for (const routine of routines) {
    if (!routine.definition) throw new Error(`Missing definition for routine ${routine.schema}.${routine.name}`);
    lines.push(routine.definition.trim());
    const kind = routine.kind === "p" ? "PROCEDURE" : "FUNCTION";
    const signature = `${quoteIdent(routine.schema)}.${quoteIdent(routine.name)}(${routine.identity_arguments})`;
    if (routine.owner) lines.push(`ALTER ${kind} ${signature} OWNER TO ${quoteIdent(routine.owner)};`);
  }
  lines.push("SET check_function_bodies = on;");
  lines.push("");

  for (const view of structure.views ?? []) {
    const relation = relations.find((r) => r.schema === view.schema && r.name === view.name);
    const options = (relation?.options ?? []).filter((x) => x === "security_invoker=true" || x === "security_barrier=true");
    const withOptions = options.length ? ` WITH (${options.join(", ")})` : "";
    lines.push(`CREATE OR REPLACE VIEW ${quoteIdent(view.schema)}.${quoteIdent(view.name)}${withOptions} AS`);
    lines.push(`${view.definition.trim().replace(/;$/, "")};`);
    if (relation?.owner) lines.push(`ALTER VIEW ${quoteIdent(view.schema)}.${quoteIdent(view.name)} OWNER TO ${quoteIdent(relation.owner)};`);
    const comment = commentLine(`VIEW ${quoteIdent(view.schema)}.${quoteIdent(view.name)}`, relation?.comment);
    if (comment) lines.push(comment);
  }
  lines.push("");

  for (const trigger of triggers) lines.push(`${trigger.definition};`);
  lines.push("");

  for (const policy of policies) {
    const roles = (policy.roles ?? []).map(quoteRole).join(", ") || "PUBLIC";
    let statement = `CREATE POLICY ${quoteIdent(policy.name)} ON ${qualified(policy.table)} AS ${policy.permissive} FOR ${policy.command} TO ${roles}`;
    if (policy.using != null) statement += ` USING (${policy.using})`;
    if (policy.with_check != null) statement += ` WITH CHECK (${policy.with_check})`;
    lines.push(statement + ";");
  }
  lines.push("");

  for (const table of tables) {
    const q = `${quoteIdent(table.schema)}.${quoteIdent(table.name)}`;
    if (table.rls_enabled) lines.push(`ALTER TABLE ${q} ENABLE ROW LEVEL SECURITY;`);
    if (table.force_rls) lines.push(`ALTER TABLE ${q} FORCE ROW LEVEL SECURITY;`);
  }
  lines.push("");

  const schemaAcl = security.schema_privileges ?? [];
  for (const schema of schemaAcl) {
    lines.push(`ALTER SCHEMA ${quoteIdent(schema.schema)} OWNER TO ${quoteIdent(schema.owner)};`);
    lines.push(`REVOKE ALL ON SCHEMA ${quoteIdent(schema.schema)} FROM PUBLIC, anon, authenticated, service_role, pg_database_owner;`);
    for (const privilege of schema.privileges ?? []) {
      lines.push(grantLine([privilege.privilege], quoteIdent(schema.schema), privilege.grantee, "SCHEMA", privilege.grantable));
    }
  }
  lines.push("");

  const relationAclByName = grouped(directRelationAcl, (p) => p.relation);
  for (const relation of relations.filter((r) => ["r", "p", "v", "m", "S", "f"].includes(r.kind))) {
    const q = `${quoteIdent(relation.schema)}.${quoteIdent(relation.name)}`;
    const isSequence = relation.kind === "S";
    const objectKind = isSequence ? "SEQUENCE" : "TABLE";
    lines.push(`REVOKE ALL ON ${objectKind} ${q} FROM PUBLIC, anon, authenticated, service_role, pg_database_owner;`);
    const acl = relationAclByName.get(`${relation.schema}.${relation.name}`) ?? [];
    for (const item of acl) {
      lines.push(grantLine([item.privilege], q, item.grantee, objectKind, item.grantable));
    }
  }
  lines.push("");

  for (const item of directColumnAcl) {
    const [schema, table] = item.table.split(".");
    lines.push(
      `GRANT ${item.privilege} (${quoteIdent(item.column)}) ON TABLE ${quoteIdent(schema)}.${quoteIdent(table)} TO ${quoteRole(item.grantee)}${item.grantable ? " WITH GRANT OPTION" : ""};`,
    );
  }
  lines.push("");

  for (const routine of routines) {
    const kind = routine.kind === "p" ? "PROCEDURE" : "FUNCTION";
    const signature = `${quoteIdent(routine.schema)}.${quoteIdent(routine.name)}(${routine.identity_arguments})`;
    lines.push(`REVOKE ALL ON ${kind} ${signature} FROM PUBLIC, anon, authenticated, service_role;`);
    for (const privilege of routine.privileges ?? []) {
      lines.push(grantLine([privilege.privilege], signature, privilege.grantee, kind, privilege.grantable));
    }
  }
  lines.push("");

  for (const defaults of security.default_privileges ?? []) {
    const owner = quoteIdent(defaults.owner);
    const schema = defaults.schema ? ` IN SCHEMA ${quoteIdent(defaults.schema)}` : "";
    const objectType = ({ r: "TABLES", S: "SEQUENCES", f: "FUNCTIONS", T: "TYPES" })[defaults.object_type];
    if (!objectType) continue;
    lines.push(`ALTER DEFAULT PRIVILEGES FOR ROLE ${owner}${schema} REVOKE ALL ON ${objectType} FROM PUBLIC, anon, authenticated, service_role;`);
    for (const privilege of defaults.privileges ?? []) {
      lines.push(`ALTER DEFAULT PRIVILEGES FOR ROLE ${owner}${schema} GRANT ${privilege.privilege} ON ${objectType} TO ${quoteRole(privilege.grantee)}${privilege.grantable ? " WITH GRANT OPTION" : ""};`);
    }
  }

  return lines.filter((line) => line !== undefined).join("\n") + "\n";
}

if (process.argv[1]?.endsWith("build-disposable-schema-fixture.mjs")) {
  const structure = JSON.parse(fs.readFileSync(ROOT + "current-state-structure.json", "utf8"));
  const routines = JSON.parse(fs.readFileSync(ROOT + "current-state-routines.json", "utf8"));
  const security = JSON.parse(fs.readFileSync(ROOT + "current-state-security.json", "utf8"));
  const grants = JSON.parse(fs.readFileSync(ROOT + "current-state-effective-grants.json", "utf8"));
  process.stdout.write(buildDisposableSchemaSql(structure, routines, security, grants));
}
