import assert from 'node:assert/strict';
import fs from 'node:fs';

const html=fs.readFileSync('index.html','utf8');
const pager=fs.readFileSync('list-pagination.js','utf8');
const css=fs.readFileSync('poyozz-ui.css','utf8');

const conversation=html;
assert.match(conversation,/loadCloudChatSessions\(owner,\{onlySessionId:sessionId,listPage:false\}\)/,
  'opening a cloud conversation must hydrate the authoritative session version before read-state sync');
assert.match(html,/if\(route\?\.overlay\)[\s\S]*?delete next\.overlay;[\s\S]*?go\(next,true\)/,
  'closing a route overlay must replace the current route without the stale overlay');
assert.match(html,/已經到底了～/,'chat list must explicitly show the end state after all pages are loaded');
assert.ok(html.includes("root:scrollRoot||null,rootMargin:'0px'"),
  'chat pagination must use the chat list as root and only trigger at the true end');
assert.ok(html.includes("range(pager.offset,pager.offset+pageSize)"),'chat list must use one-row lookahead to avoid a false has-more state');
assert.ok(html.includes("range(g.groupListOffset,g.groupListOffset+pageSize)"),'group list must use one-row lookahead');
assert.ok(html.includes("findExistingStoryChatSessionFallback(client,userId,characterId)"),'missing Story lookup RPC must fall back to bounded owner-scoped reads');
assert.ok(html.includes("confirmedUserMessageSessionIds.has(row.id)"),'legacy false user-message markers must not hide existing chats');
assert.match(html,/data-history-top-control hidden/,'older message controls must remain hidden until the reader reaches the top');
assert.match(html,/character-visibility-choice/,'character visibility must use explicit selected controls');
assert.match(pager,/function observeEnd[\s\S]*?for\(let p=node\.parentElement/);
assert.match(pager,/getComputedStyle\(p\)/);
assert.match(html,/group-picker-avatar/);
assert.match(html,/image\.replaceWith\(fallback\)/,'broken group portraits must fall back to a character initial');
assert.match(css,/\.chat-list \.chat-entry \{[^}]*min-height:68px/,
  'chat list rows must be compact and consistently aligned');
assert.match(css,/border-bottom:1px solid rgba\(255,255,255,\.055\)/,
  'chat list should use a subtle separator rather than individual card borders');
assert.match(css,/\.character-visibility-option:has\(input:checked\)/,
  'selected public/private option must be marked with a purple outline');
assert.doesNotMatch(css.slice(css.indexOf('/* Refined chat-list rows')),/\.message[^}]*width:/,
  'PR #256 must not modify chat message widths');
console.log('PR #256 conversation, overlay, pagination, avatar and chat-list regressions passed.');

assert.match(html,/completedBatches=new Set\(memories\.filter\(m=>m\.autoGenerated&&Number\(m\.sourceUserCount\)>0\)/,'deleted auto-generated group diary batches must retain a non-visible tombstone and not be recreated on reopen');
assert.match(html,/if\(memory\.autoGenerated\)\{memory\.deleted=true;memory\.text='';\}/,'deleting a generated group diary entry must persist a batch tombstone');
assert.match(html,/visibleMemories=memories\.filter\(m=>!m\.deleted\)/,'deleted group diary tombstones must not be rendered or counted');

assert.match(html,/for\(let attempt=0;attempt<2;attempt\+\+\)/,'pin sync retries once after a concurrent version update');

assert.match(css,/\.chat-list \.chat-entry\s*\{[^}]*min-height:68px/);
assert.match(css,/\.character-visibility-option:has\(input:checked\)/);
